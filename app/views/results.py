"""Results page — recommendation card + 5 analysis tabs."""
from __future__ import annotations

import pandas as pd
import streamlit as st

from api_client import ApiError, advisor, recommendation, rerank
from components.charts_view import (
    framework_internals,
    overview_charts,
    radar_chart,
    sensitivity_chart,
    time_cost_charts,
)
from components.metrics_table import render_metrics_table
from components.recommendation_card import recommendation_card


def render() -> None:
    st.header("📈 Results")

    exp_id_default = int(st.session_state.get("experiment_id") or 1)
    exp_id = st.number_input("Experiment ID", min_value=1, value=exp_id_default, key="res_exp_id")

    try:
        rec = recommendation(int(exp_id))
    except ApiError as exc:
        st.info("Run a benchmark first, or check the experiment ID.")
        st.caption(str(exc))
        return

    # ── Recommendation card ─────────────────────────────────────────────────
    recommendation_card(rec)

    # ── AI advisor (Respan gateway; optional) ───────────────────────────────
    with st.expander("🧠 Ask the Advisor", expanded=False):
        question = st.text_input(
            "Question (optional)",
            key="res_advisor_q",
            placeholder="Explain this recommendation",
        )
        if st.button("Explain with the advisor", key="res_advisor_btn"):
            try:
                answer = advisor(int(exp_id), question or None)
                st.session_state.res_advisor_answer = answer
            except ApiError as exc:
                st.session_state.res_advisor_answer = None
                st.info("The AI advisor is unavailable; the explanation above still applies.")
                st.caption(str(exc))
        answer = st.session_state.get("res_advisor_answer")
        if answer:
            st.markdown(answer["narrative"])
            st.caption(f"Generated by {answer.get('model')} through the Respan gateway.")

    # Rerank sidebar
    with st.sidebar:
        st.markdown("---")
        st.subheader("🔁 Live Rerank")
        rr_preset = st.selectbox(
            "Priority preset",
            ["balanced", "max_accuracy", "fast_inference", "interpretable", "imbalance_safe"],
            key="res_rr_preset",
        )
        if st.button("Apply new priorities", key="res_rr_btn"):
            try:
                rec = rerank(int(exp_id), {"preset": rr_preset})
                st.session_state.last_rerank = rec
                st.rerun()
            except ApiError as exc:
                st.error(str(exc))

    # ── Build DataFrame ─────────────────────────────────────────────────────
    score_table = rec.get("score_table") or []
    df = pd.DataFrame(score_table)

    # ── Tabs ────────────────────────────────────────────────────────────────
    tab_names = [
        "📊 Overview",
        "🕸 Radar",
        "⏱ Time & Cost",
        "📋 Leaderboard",
        "🎚 Sensitivity",
        "🔬 Framework Internals",
    ]
    tabs = st.tabs(tab_names)

    with tabs[0]:
        overview_charts(df)

    with tabs[1]:
        top_n = st.slider("Top-N models", 3, min(10, max(3, len(df))), min(6, len(df)), key="res_radar_n")
        radar_chart(df, top_n=top_n)

    with tabs[2]:
        time_cost_charts(df)

    with tabs[3]:
        render_metrics_table(df)

    with tabs[4]:
        sensitivity_chart(score_table)

    with tabs[5]:
        framework_internals(df)
